"""Build data/people.yaml: hand-maintained roles (data/people.base.yaml) plus recorded votes.

City members get their votes on the final 2026 budget motions, read from the City's
council voting-record Open Data. Votes are quoted as recorded, without interpretation.

Usage:
    uv run python -m pipeline.people
"""
from __future__ import annotations

import pandas as pd
import yaml

from .common import AS_OF, DATA, raw_path, source

VOTES_ID = "toronto-council-votes-2022-2026"
VOTES_DATASET_URL = "https://open.toronto.ca/dataset/members-of-toronto-city-council-voting-record/"
# The two final votes on the 2026 budget item, 2026-02-10 (exact "Vote Description" text).
BUDGET_VOTES = [
    ("Majority required - CC38.1 - Adoption of Recommendations 1 to 4 as amended - Revote",
     "2026 City budget (item 2026.CC38.1): adoption of Recommendations 1 to 4 as amended (revote)"),
    ("Majority required - CC38.1 - Adopt balance of the item as amended",
     "2026 City budget (item 2026.CC38.1): adoption of the rest of the item as amended"),
]
VOTE = {"Yes": "yes", "No": "no", "Absent": "absent"}


def city_decisions(votes: pd.DataFrame, first: str, last: str) -> list[dict]:
    out = []
    for desc, what in BUDGET_VOTES:
        rows = votes[(votes["Vote Description"] == desc) & (votes["First Name"] == first) & (votes["Last Name"] == last)]
        if len(rows) != 1:
            raise ValueError(f"expected one recorded vote for {first} {last} on {desc!r}, found {len(rows)}")
        r = rows.iloc[0]
        out.append(
            {
                "date": str(r["Date/Time"])[:10],
                "what": f"{what}. Result: {r['Result']}.",
                "vote": VOTE[r["Vote"]],
                "item": r["Agenda Item #"],
                "source": {"title": "City Council voting record (Open Data)", "url": VOTES_DATASET_URL},
            }
        )
    return out


def main() -> int:
    base = yaml.safe_load((DATA / "people.base.yaml").read_text())
    votes = pd.read_csv(raw_path(VOTES_ID), low_memory=False)
    votes = votes[votes["Agenda Item #"] == "2026.CC38.1"]
    people = []
    for p in base:
        p = dict(p)
        name = p.pop("vote_name", None)
        if p["level"] == "city":
            if not name:
                raise ValueError(f"{p['id']}: city members need vote_name for the voting record")
            p["decisions"] = city_decisions(votes, *name)
        p.setdefault("decisions", [])
        p.setdefault("quotes", [])
        p["as_of"] = AS_OF
        people.append(p)
    header = (
        "# GENERATED by pipeline/people.py from data/people.base.yaml and "
        f"{source(VOTES_ID)['title']}. Do not edit by hand.\n"
    )
    (DATA / "people.yaml").write_text(header + yaml.safe_dump(people, sort_keys=False, allow_unicode=True, width=120))
    print(f"wrote data/people.yaml ({len(people)} people)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
